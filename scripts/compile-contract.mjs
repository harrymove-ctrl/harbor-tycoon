import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const FORGE_BIN = process.env.FORGE_BIN || '/Users/harryphan/.foundry/bin/forge';

const OFFICIAL_WIF_MAINNET = '0x5173b8eA6923c2d40267890D45C46a3480954773';

execFileSync(FORGE_BIN, ['build'], { cwd: ROOT, stdio: 'inherit' });

const solPath = path.join(ROOT, 'contracts', 'RobinTownHarborVault.sol');
const outPath = path.join(
  ROOT,
  'contracts',
  'out',
  'RobinTownHarborVault.sol',
  'RobinTownHarborVault.json',
);

const soliditySource = fs.readFileSync(solPath, 'utf8');
const compiled = JSON.parse(fs.readFileSync(outPath, 'utf8'));

const creationBytecode = String(compiled.bytecode.object).replace(/^0x/, '').toLowerCase();
const rawDeployedBytecode = String(compiled.deployedBytecode.object)
  .replace(/^0x/, '')
  .toLowerCase();
const immutableRefs = compiled.deployedBytecode.immutableReferences || {};

// Encode constructor argument: address wifTokenAddress = OFFICIAL_WIF_MAINNET (32-byte ABI word)
const encodedWifArg = OFFICIAL_WIF_MAINNET.slice(2).toLowerCase().padStart(64, '0');
const creationTxDataMainnet = `0x${creationBytecode}${encodedWifArg}`;

// Splice immutable wif address into deployedBytecode to compute exact expected runtime bytecode
const runtimeChars = rawDeployedBytecode.split('');
for (const refs of Object.values(immutableRefs)) {
  for (const ref of refs) {
    const hexStart = ref.start * 2;
    const hexLen = ref.length * 2;
    for (let i = 0; i < hexLen; i += 1) {
      runtimeChars[hexStart + i] = encodedWifArg[i];
    }
  }
}
const expectedMainnetRuntimeHex = `0x${runtimeChars.join('')}`;
const expectedMainnetRuntimeSha256 = crypto
  .createHash('sha256')
  .update(expectedMainnetRuntimeHex.slice(2), 'hex')
  .digest('hex');

const compilerVersion = `v${compiled.metadata.compiler.version}`;
const evmVersion = compiled.metadata.settings.evmVersion || 'paris';
const optimizerEnabled = Boolean(compiled.metadata.settings.optimizer?.enabled);
const optimizerRuns = Number(compiled.metadata.settings.optimizer?.runs ?? 200);

const artifactModule = `// Auto-generated by scripts/compile-contract.mjs from contracts/RobinTownHarborVault.sol
// Compiler: ${compilerVersion}, EVM: ${evmVersion}, Optimizer: ${optimizerEnabled} (${optimizerRuns} runs)

export const VAULT_CONTRACT_METADATA = {
  contractName: 'RobinTownHarborVault',
  tokenName: 'Robin Town',
  tokenSymbol: 'RTOWN',
  decimals: 18,
  chainId: 4663,
  officialWifMainnet: '${OFFICIAL_WIF_MAINNET}',
  compilerVersion: '${compilerVersion}',
  evmVersion: '${evmVersion}',
  optimizerEnabled: ${optimizerEnabled},
  optimizerRuns: ${optimizerRuns},
  creationBytecodeBytes: ${creationBytecode.length / 2},
  deployedBytecodeBytes: ${rawDeployedBytecode.length / 2},
  expectedMainnetRuntimeSha256: '${expectedMainnetRuntimeSha256}',
};

export const VAULT_CONTRACT_ABI = ${JSON.stringify(compiled.abi, null, 2)};

export const VAULT_CREATION_TX_DATA_MAINNET = '${creationTxDataMainnet}';

export const VAULT_EXPECTED_MAINNET_RUNTIME_HEX = '${expectedMainnetRuntimeHex}';

export const VAULT_SOLIDITY_SOURCE = ${JSON.stringify(soliditySource)};
`;

const targetPath = path.join(ROOT, 'scripts', 'contract-artifact.mjs');
fs.writeFileSync(targetPath, artifactModule, 'utf8');
console.log(
  `Generated scripts/contract-artifact.mjs (${creationBytecode.length / 2}B creation, sha256=${expectedMainnetRuntimeSha256.slice(0, 16)}…)`,
);
